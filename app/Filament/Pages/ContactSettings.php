<?php

namespace App\Filament\Pages;

use App\Models\Contact;
use App\Models\User;
use App\Services\Ares\AresCompanyLookup;
use App\Services\Ares\AresLookupException;
use BezhanSalleh\FilamentShield\Support\Utils;
use Filament\Actions\Action;
use Filament\Forms\Components\TextInput;
use Filament\Notifications\Notification;
use Filament\Pages\Page;
use Filament\Schemas\Components\Actions;
use Filament\Schemas\Components\EmbeddedSchema;
use Filament\Schemas\Components\Form;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;
use Filament\Support\Components\Attributes\Exposed;
use Filament\Support\Icons\Heroicon;
use Illuminate\Support\Facades\Log;

/**
 * Singular administration page for the single contact record rendered on the public /kontakt page.
 *
 * @property-read Schema $form
 */
class ContactSettings extends Page
{
    /**
     * Page permission generated by Filament Shield (`php artisan shield:generate --all`).
     *
     * The permission row does not exist until it is generated, so the super admin role fallback in canAccess()
     * keeps this page reachable for the administrator in the meantime.
     */
    private const PERMISSION = 'View:ContactSettings';

    /**
     * @var array<string, mixed> | null
     */
    public ?array $data = [];

    protected static string|\BackedEnum|null $navigationIcon = Heroicon::OutlinedIdentification;

    protected static string|\UnitEnum|null $navigationGroup = 'Nastavení';

    protected static ?string $navigationLabel = 'Kontaktní údaje';

    protected static ?string $title = 'Údaje na stránce Kontakt';

    protected static ?string $breadcrumb = 'Kontakt';

    protected static ?int $navigationSort = 10;

    /**
     * Shield is configured with `super_admin.define_via_gate = false`, so the super admin role is not intercepted by
     * the gate and needs an explicit permission. A page permission that has not been generated yet would therefore
     * hide this page even for the administrator, hence the role fallback next to the granular permission check.
     */
    public static function canAccess(): bool
    {
        $user = auth()->user();

        if (! $user instanceof User) {
            return false;
        }

        return $user->can(self::PERMISSION) || $user->hasRole(Utils::getSuperAdminName());
    }

    public function mount(): void
    {
        // Only the editable attributes are filled, so model keys never leak into the form state.
        $this->form->fill(Contact::current()->only(array_keys(Contact::defaultAttributes())));
    }

    public function form(Schema $schema): Schema
    {
        return $schema
            ->statePath('data')
            ->components([
                Section::make('Firma')
                    ->schema([
                        TextInput::make('company_name')
                            ->label('Název firmy')
                            ->required()
                            ->maxLength(255),
                        TextInput::make('street')
                            ->label('Ulice a číslo popisné')
                            ->required()
                            ->maxLength(255),
                        TextInput::make('city')
                            ->label('PSČ a obec')
                            ->required()
                            ->maxLength(255),
                    ])
                    ->columns(2),
                Section::make('Kontaktní údaje')
                    ->schema([
                        TextInput::make('contact_person')
                            ->label('Kontaktní osoba')
                            ->required()
                            ->maxLength(255),
                        TextInput::make('email')
                            ->label('E-mail')
                            ->email()
                            ->required()
                            ->maxLength(255),
                        TextInput::make('phone')
                            ->label('Telefon')
                            ->tel()
                            ->required()
                            ->maxLength(255),
                    ])
                    ->columns(2),
                Section::make('Registrační údaje')
                    ->schema([
                        TextInput::make('registration_number')
                            ->label('IČ')
                            ->required()
                            ->maxLength(255),
                        TextInput::make('vat_number')
                            ->label('DIČ')
                            ->required()
                            ->maxLength(255),
                        TextInput::make('data_box')
                            ->label('Datová schránka')
                            ->required()
                            ->maxLength(255),
                        TextInput::make('bank_account')
                            ->label('Číslo účtu')
                            ->required()
                            ->maxLength(255),
                        TextInput::make('registry_note')
                            ->label('Zápis v obchodním rejstříku')
                            ->required()
                            ->maxLength(255)
                            ->columnSpanFull(),
                    ])
                    ->columns(2),
                Section::make('Odkazy na mapy')
                    ->schema([
                        TextInput::make('google_maps_url')
                            ->label('Google Maps')
                            ->url()
                            ->required()
                            ->maxLength(255)
                            ->columnSpanFull(),
                        TextInput::make('waze_url')
                            ->label('Waze')
                            ->url()
                            ->required()
                            ->maxLength(255)
                            ->columnSpanFull(),
                        TextInput::make('seznam_maps_url')
                            ->label('Seznam Mapy')
                            ->url()
                            ->required()
                            ->maxLength(255)
                            ->columnSpanFull(),
                    ]),
            ]);
    }

    public function content(Schema $schema): Schema
    {
        return $schema
            ->components([
                Form::make([
                    EmbeddedSchema::make('form'),
                ])
                    ->id('form')
                    ->livewireSubmitHandler('save')
                    ->footer([
                        Actions::make([
                            Action::make('save')
                                ->label('Uložit')
                                ->submit('save')
                                ->keyBindings(['mod+s']),
                        ]),
                    ]),
            ]);
    }

    /**
     * Page level actions are rendered in the page header. The ARES import lives here because it only prefills the
     * form below and nothing is persisted until the administrator submits it.
     *
     * @return array<int, Action>
     */
    protected function getHeaderActions(): array
    {
        return [
            Action::make('loadFromAres')
                ->label('Načíst z ARES')
                ->icon(Heroicon::OutlinedCloudArrowDown)
                ->color('gray')
                ->modalHeading('Načíst údaje z ARES')
                ->modalDescription('Zadejte IČ. Načtou se pouze údaje, které ARES vrací, ostatní pole zůstanou beze změny.')
                ->modalSubmitActionLabel('Načíst')
                ->visible(fn (): bool => static::canAccess())
                ->schema([
                    TextInput::make('ico')
                        ->label('IČ')
                        ->required()
                        ->rule('digits:8')
                        ->validationMessages([
                            'required' => 'Zadejte IČ.',
                            'digits' => 'IČ musí obsahovat přesně osm číslic.',
                        ]),
                ])
                ->fillForm(fn (): array => [
                    'ico' => (string) ($this->data['registration_number'] ?? ''),
                ])
                ->action(function (array $data): void {
                    $this->importFromAres((string) ($data['ico'] ?? ''));
                }),
        ];
    }

    /**
     * Prefill the form with the values ARES actually returns.
     *
     * Only the returned keys are replaced, so every manually maintained value (contact person, e-mail, phone, map
     * links, data box, bank account, registry note and anything ARES did not send) stays untouched. The record is not
     * saved here on purpose: the standard "Uložit" action remains the only way to persist the form.
     */
    public function importFromAres(string $registrationNumber): void
    {
        abort_unless(static::canAccess(), 403);

        $registrationNumber = trim($registrationNumber);

        try {
            $attributes = app(AresCompanyLookup::class)->forRegistrationNumber($registrationNumber);
        } catch (AresLookupException $exception) {
            // Only the IČ and the failure category are logged, never the upstream payload or the exception trace.
            Log::warning('ARES import failed.', [
                'ico' => $registrationNumber,
                'reason' => $exception->reason,
            ]);

            Notification::make()
                ->danger()
                ->title('Údaje z ARES se nepodařilo načíst')
                ->body($exception->getMessage())
                ->send();

            return;
        }

        $this->form->fill(array_merge($this->data ?? [], $attributes));

        Notification::make()
            ->success()
            ->title('Údaje z ARES byly načteny')
            ->body('Zkontrolujte je prosím a uložte tlačítkem Uložit.')
            ->send();
    }

    /**
     * Update the singleton record in place, so the page can never multiply contact rows.
     */
    #[Exposed]
    public function save(): void
    {
        $contact = Contact::current();

        $contact->update($this->form->getState());

        Notification::make()
            ->success()
            ->title('Údaje na stránce Kontakt byly uloženy')
            ->send();
    }
}
