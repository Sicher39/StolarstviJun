<?php

namespace App\Filament\Pages;

use App\Models\MailSetting;
use App\Models\User;
use App\Services\Mail\MailSettingsMailer;
use App\Services\Mail\SmtpConnectionTester;
use BezhanSalleh\FilamentShield\Support\Utils;
use Filament\Actions\Action;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Notifications\Notification;
use Filament\Pages\Page;
use Filament\Schemas\Components\Actions;
use Filament\Schemas\Components\EmbeddedSchema;
use Filament\Schemas\Components\Form;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Components\Text;
use Filament\Schemas\Schema;
use Filament\Support\Components\Attributes\Exposed;
use Filament\Support\Icons\Heroicon;
use Illuminate\Support\Facades\RateLimiter;

/**
 * Singular administration page for the mailbox the application sends its e-mail through.
 *
 * The whole connection is maintained here - the sender, the outgoing (SMTP) server and the incoming (POP3) server - so
 * nothing of it has to be part of `.env` and the office can change it without the server. The receiving side is stored
 * for the office only: the application does not open a POP3 session yet, there is no inbox import.
 *
 * Both passwords are write-only. A stored secret is never sent back into the form and an empty field keeps it
 * untouched, so opening the screen and saving it can never wipe the credentials of a working mailbox. The reveal button
 * of the two password fields therefore only shows the value that is being typed before it is saved.
 *
 * Both passwords are trimmed at their edges, just like the address and the user names: a pasted secret usually carries
 * an invisible space that the server refuses on login. Only the whitespace around the secret is removed - a space inside
 * a password is a part of it.
 *
 * @property-read Schema $form
 */
class MailSettings extends Page
{
    /**
     * Page permission generated by Filament Shield (`php artisan shield:generate --all`).
     *
     * The permission row does not exist until it is generated, so the super admin role fallback in canAccess() keeps
     * this page reachable for the administrator in the meantime.
     */
    private const PERMISSION = 'View:MailSettings';

    /**
     * Every test opens a real connection to the server of the mailbox, so one busy button cannot hammer it.
     */
    private const TestAttemptsPerMinute = 3;

    /**
     * @var array<string, mixed> | null
     */
    public ?array $data = [];

    protected static string|\BackedEnum|null $navigationIcon = Heroicon::OutlinedEnvelope;

    protected static string|\UnitEnum|null $navigationGroup = 'Nastavení';

    protected static ?string $navigationLabel = 'E-mailová schránka';

    protected static ?string $title = 'Nastavení e-mailové schránky';

    protected static ?string $breadcrumb = 'E-mail';

    protected static ?int $navigationSort = 30;

    /**
     * Shield is configured with `super_admin.define_via_gate = false`, so the super admin role is not intercepted by the
     * gate and needs an explicit permission. A page permission that has not been generated yet would therefore hide this
     * page even for the administrator, hence the role fallback next to the granular permission check.
     */
    public static function canAccess(): bool
    {
        $user = auth()->user();

        if (! $user instanceof User) {
            return false;
        }

        return $user->can(self::PERMISSION) || $user->hasRole(Utils::getSuperAdminName());
    }

    public function mount(): void
    {
        $settings = MailSetting::current();

        // Only the editable attributes are filled, so model keys never leak into the form state. The passwords are
        // missing from the list on purpose: they are write-only.
        $this->form->fill($settings->only(MailSetting::EDITABLE_ATTRIBUTES));
    }

    public function form(Schema $schema): Schema
    {
        return $schema
            ->statePath('data')
            ->components([
                Section::make('Používání schránky')
                    ->description('Zapnutá a úplně vyplněná schránka nahradí nastavení z .env, takže přihlašovací údaje k e-mailu už na serveru potřeba nejsou. Vypnutá nebo neúplná schránka nastavení z .env nemění.')
                    ->schema([
                        Toggle::make('enabled')
                            ->label('Používat tuto schránku'),
                        Text::make('Uložení samo nic neodešle ani nestáhne. Ověření spojení spustíte tlačítkem „Otestovat SMTP spojení“ v hlavičce stránky.'),
                    ]),
                Section::make('Odesílatel')
                    ->description('Údaje, se kterými e-maily odcházejí. Adresa musí patřit ke schránce, jinak ji server odmítne.')
                    ->schema([
                        TextInput::make('from_address')
                            ->label('Adresa odesílatele (From)')
                            ->email()
                            ->maxLength(255)
                            ->autocomplete(false)
                            // A space around the address would end up in the header of every message.
                            ->trim()
                            ->helperText('Adresa, ze které e-maily odcházejí.'),
                        TextInput::make('from_name')
                            ->label('Jméno odesílatele')
                            ->maxLength(255)
                            ->autocomplete(false)
                            ->trim(),
                    ])
                    ->columns(2),
                Section::make('Odesílání (SMTP)')
                    ->description('Server, přes který e-maily odcházejí.')
                    ->schema([
                        TextInput::make('smtp_host')
                            ->label('Server')
                            ->maxLength(255)
                            ->autocomplete(false)
                            ->trim()
                            ->placeholder('smtp.example.com'),
                        TextInput::make('smtp_port')
                            ->label('Port')
                            ->numeric()
                            ->minValue(1)
                            ->maxValue(65535)
                            ->placeholder((string) MailSetting::SMTP_DEFAULT_PORT),
                        Select::make('smtp_encryption')
                            ->label('Zabezpečení')
                            ->options(MailSetting::ENCRYPTIONS)
                            ->default(MailSetting::ENCRYPTION_TLS),
                        TextInput::make('smtp_username')
                            ->label('Uživatelské jméno')
                            ->maxLength(255)
                            ->autocomplete(false)
                            // The space is invisible in the field but the server refuses the login with it.
                            ->trim(),
                        TextInput::make('smtp_password')
                            ->label('Heslo')
                            ->password()
                            // The eye button only reveals the value being typed right now, never a stored secret.
                            ->revealable()
                            ->maxLength(255)
                            ->autocomplete(false)
                            // A pasted secret usually carries a space at either end, and the server then refuses the
                            // login. Only the edges are trimmed, a space inside the password is kept.
                            ->trim()
                            // A stored secret is never sent back to the browser: the field starts empty and an empty
                            // field keeps the stored password untouched.
                            ->formatStateUsing(static fn (): ?string => null)
                            // A field of whitespace only is blank as well, so it is not written either - the trim would
                            // otherwise turn it into an empty value and wipe a working credential.
                            ->dehydrated(static fn (?string $state): bool => MailSetting::normalizedSecret($state) !== null)
                            ->helperText(fn (): string => $this->hasStoredSecret('smtp_password')
                                ? 'Heslo je uložené. Ponechte pole prázdné, pokud ho nechcete změnit.'
                                : 'Zatím není uložené žádné heslo.'),
                    ])
                    ->columns(3),
                Section::make('Příjem (POP3)')
                    ->description('Server, ze kterého se má pošta stahovat. Aplikace dnes poštu nestahuje - údaje se ukládají pro přehled a pro budoucí napojení schránky, nic je zatím nečte.')
                    ->schema([
                        TextInput::make('pop3_host')
                            ->label('Server')
                            ->maxLength(255)
                            ->autocomplete(false)
                            ->trim()
                            ->placeholder('pop3.example.com'),
                        TextInput::make('pop3_port')
                            ->label('Port')
                            ->numeric()
                            ->minValue(1)
                            ->maxValue(65535)
                            ->placeholder((string) MailSetting::POP3_DEFAULT_PORT),
                        Select::make('pop3_encryption')
                            ->label('Zabezpečení')
                            ->options(MailSetting::ENCRYPTIONS)
                            ->default(MailSetting::ENCRYPTION_SSL),
                        TextInput::make('pop3_username')
                            ->label('Uživatelské jméno')
                            ->maxLength(255)
                            ->autocomplete(false)
                            ->trim(),
                        TextInput::make('pop3_password')
                            ->label('Heslo')
                            ->password()
                            ->revealable()
                            ->maxLength(255)
                            ->autocomplete(false)
                            // The same edge rule as the sending side, so a pasted space never becomes part of the secret.
                            ->trim()
                            ->formatStateUsing(static fn (): ?string => null)
                            // The same blank rule as the sending side: whitespace only means "keep the stored secret".
                            ->dehydrated(static fn (?string $state): bool => MailSetting::normalizedSecret($state) !== null)
                            ->helperText(fn (): string => $this->hasStoredSecret('pop3_password')
                                ? 'Heslo je uložené. Ponechte pole prázdné, pokud ho nechcete změnit.'
                                : 'Zatím není uložené žádné heslo.'),
                    ])
                    ->columns(3),
                Section::make('Stav napojení')
                    ->description('Stav vychází z uložených údajů, ne z neuloženého formuláře.')
                    ->schema([
                        Text::make(static function (): string {
                            $settings = MailSetting::configured();

                            return match (true) {
                                $settings === null => 'Odesílání: zatím nejsou uložené žádné údaje.',
                                $settings->canSendMail() => 'Odesílání: připraveno.',
                                default => 'Odesílání: není kompletní, aplikace zatím používá nastavení z .env.',
                            };
                        }),
                        Text::make(static function (): string {
                            $settings = MailSetting::configured();

                            return match (true) {
                                $settings === null => '',
                                $settings->canReceiveMail() => 'Příjem (POP3): údaje jsou vyplněné.',
                                default => 'Příjem (POP3): údaje nejsou kompletní.',
                            };
                        }),
                    ])
                    ->columns(2),
            ]);
    }

    public function content(Schema $schema): Schema
    {
        return $schema
            ->components([
                Form::make([
                    EmbeddedSchema::make('form'),
                ])
                    ->id('form')
                    ->livewireSubmitHandler('save')
                    ->footer([
                        Actions::make([
                            Action::make('save')
                                ->label('Uložit')
                                ->submit('save')
                                ->keyBindings(['mod+s']),
                        ]),
                    ]),
            ]);
    }

    /**
     * Page level actions are rendered in the page header. The connection test lives here because it only asks the
     * server about the values in the form and never writes anything.
     *
     * @return array<int, Action>
     */
    protected function getHeaderActions(): array
    {
        return [
            Action::make('testSmtpConnection')
                ->label('Otestovat SMTP spojení')
                ->icon(Heroicon::OutlinedSignal)
                ->color('gray')
                ->tooltip('Ověří spojení, zabezpečení a přihlášení k SMTP serveru s hodnotami z formuláře. E-mail se neodesílá a nastavení se neukládá.')
                ->visible(fn (): bool => static::canAccess())
                ->action(function (): void {
                    $this->testSmtpConnection();
                }),
        ];
    }

    /**
     * Store the mailbox in the singleton record and make the new settings effective at once.
     */
    #[Exposed]
    public function save(): void
    {
        abort_unless(static::canAccess(), 403);

        $settings = MailSetting::current();

        $settings->update($this->form->getState());

        // The mail configuration is built from this row, so the mailer this process may already hold is rebuilt.
        app(MailSettingsMailer::class)->register();

        Notification::make()
            ->success()
            ->title('Nastavení e-mailové schránky bylo uloženo')
            ->send();
    }

    /**
     * Ask the server whether the settings in the form work.
     *
     * The check runs on a transient copy of the row, so the stored settings and `updated_at` stay untouched, and a typed
     * password is used by this one session only and is then forgotten.
     */
    private function testSmtpConnection(): void
    {
        abort_unless(static::canAccess(), 403);

        $settings = MailSetting::current();

        $limiterKey = 'mail-settings-smtp-test:'.(auth()->id() ?? 'guest');

        if (RateLimiter::tooManyAttempts($limiterKey, self::TestAttemptsPerMinute)) {
            Notification::make()
                ->title('Test SMTP spojení se spouští příliš často')
                ->body('Každý test otevírá skutečné spojení k serveru. Zkuste to znovu za minutu.')
                ->warning()
                ->send();

            return;
        }

        RateLimiter::hit($limiterKey);

        $result = app(SmtpConnectionTester::class)->test($this->draftSetting($settings));

        Notification::make()
            ->title($result->title())
            ->body($result->body())
            ->color($result->color())
            ->send();
    }

    /**
     * A transient copy of the stored row with the values that are in the form right now.
     *
     * The copy is never saved, so the row keeps its `updated_at` and the write-only password rule holds: an empty
     * password field keeps the stored secret, and a typed one is used by this test only. A cleared or non-numeric port
     * falls back to the usual port of the chosen encryption, exactly like an empty column does.
     */
    private function draftSetting(MailSetting $settings): MailSetting
    {
        $draft = clone $settings;

        $storedEncryption = $settings->smtp_encryption ?? MailSetting::ENCRYPTION_TLS;
        $typedPassword = $this->formState('smtp_password');

        $draft->fill([
            // The identity values are trimmed here as well, so the connection is opened with the value the row would
            // store and not with the invisible space a paste leaves in the field.
            'from_address' => MailSetting::normalizedIdentity($this->formState('from_address')),
            'from_name' => MailSetting::normalizedIdentity($this->formState('from_name')),
            'smtp_host' => MailSetting::normalizedIdentity($this->formState('smtp_host')),
            'smtp_port' => $this->formPort('smtp_port'),
            'smtp_encryption' => $this->formEncryption('smtp_encryption', $storedEncryption),
            'smtp_username' => MailSetting::normalizedIdentity($this->formState('smtp_username')),
            // A blank field means "keep the stored secret", a typed one is the password to test.
            'smtp_password' => MailSetting::normalizedSecret($typedPassword)
                ?? MailSetting::normalizedSecret($settings->smtp_password),
        ]);

        return $draft;
    }

    /**
     * Whether a secret is already stored, read from the raw column so the helper text of a password field never
     * decrypts a secret or sends it back into the browser. It is asked on every render, because a private property of a
     * Livewire component does not survive the next request.
     */
    private function hasStoredSecret(string $attribute): bool
    {
        return filled(MailSetting::configured()?->getRawOriginal($attribute));
    }

    /**
     * One value of the form as it stands, before any validation or dehydration.
     */
    private function formState(string $attribute): ?string
    {
        $value = $this->data[$attribute] ?? null;

        return is_string($value) ? $value : null;
    }

    private function formPort(string $attribute): ?int
    {
        $port = $this->data[$attribute] ?? null;

        return is_numeric($port) ? (int) $port : null;
    }

    /**
     * The encryption of the form. A value the select could never offer falls back to the stored one, so an unsaved
     * change of the select can never build a connection the row would not.
     */
    private function formEncryption(string $attribute, string $fallback): string
    {
        $value = $this->formState($attribute);

        return $value !== null && array_key_exists($value, MailSetting::ENCRYPTIONS) ? $value : $fallback;
    }
}
