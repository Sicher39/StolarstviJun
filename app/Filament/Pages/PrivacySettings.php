<?php

namespace App\Filament\Pages;

use App\Models\PrivacySetting;
use App\Models\User;
use BezhanSalleh\FilamentShield\Support\Utils;
use Filament\Actions\Action;
use Filament\Forms\Components\TextInput;
use Filament\Notifications\Notification;
use Filament\Pages\Page;
use Filament\Schemas\Components\Actions;
use Filament\Schemas\Components\EmbeddedSchema;
use Filament\Schemas\Components\Form;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;
use Filament\Support\Components\Attributes\Exposed;
use Filament\Support\Icons\Heroicon;

/**
 * Singular administration page for the privacy decisions that are not part of the legal text.
 *
 * Today it holds the inquiry retention period. The page deliberately contains no "run now" button:
 * anonymization of personal data stays a manual console step (`gdpr:anonymize-inquiries`), so it
 * can not be triggered by a misclick.
 *
 * @property-read Schema $form
 */
class PrivacySettings extends Page
{
    /**
     * Page permission generated by Filament Shield (`php artisan shield:generate --all`), with the
     * same super admin fallback the ContactSettings page uses.
     */
    private const PERMISSION = 'View:PrivacySettings';

    /**
     * @var array<string, mixed> | null
     */
    public ?array $data = [];

    protected static string|\BackedEnum|null $navigationIcon = Heroicon::OutlinedShieldCheck;

    protected static string|\UnitEnum|null $navigationGroup = 'Nastavení';

    protected static ?string $navigationLabel = 'Ochrana osobních údajů';

    protected static ?string $title = 'Nastavení ochrany osobních údajů';

    protected static ?string $breadcrumb = 'Ochrana údajů';

    protected static ?int $navigationSort = 20;

    public static function canAccess(): bool
    {
        $user = auth()->user();

        if (! $user instanceof User) {
            return false;
        }

        return $user->can(self::PERMISSION) || $user->hasRole(Utils::getSuperAdminName());
    }

    public function mount(): void
    {
        $this->form->fill(PrivacySetting::current()->only(['inquiry_retention_months']));
    }

    public function form(Schema $schema): Schema
    {
        return $schema
            ->statePath('data')
            ->components([
                Section::make('Uchovávání poptávek')
                    ->description('Doba, po které se poptávky z konfigurátoru anonymizují. Vstupuje do textu zásad jako proměnná {{ inquiry_retention_period }}.')
                    ->schema([
                        TextInput::make('inquiry_retention_months')
                            ->label('Doba uchovávání poptávek (měsíce)')
                            ->numeric()
                            ->integer()
                            ->minValue(1)
                            ->maxValue(PrivacySetting::MAX_RETENTION_MONTHS)
                            ->nullable()
                            ->helperText('Prázdné pole znamená, že doba není rozhodnuta: v textu zásad zůstane [DOPLNIT: doba uchovávání poptávek] a anonymizaci nelze spustit.'),
                    ]),
                Section::make('Anonymizace')
                    ->description('Anonymizace se nespouští automaticky ani z tohoto panelu. Po nastavení doby ji spusťte ručně na serveru: nejdřív příkazem php artisan gdpr:anonymize-inquiries --dry-run (kontrola počtu) a potom php artisan gdpr:anonymize-inquiries --force (provedení). Anonymizují se pouze poptávky z konfigurátoru: jméno, e-mail, telefon a zpráva se nahradí, konfigurace a orientační cena zůstanou.')
                    ->schema([]),
            ]);
    }

    public function content(Schema $schema): Schema
    {
        return $schema
            ->components([
                Form::make([
                    EmbeddedSchema::make('form'),
                ])
                    ->id('form')
                    ->livewireSubmitHandler('save')
                    ->footer([
                        Actions::make([
                            Action::make('save')
                                ->label('Uložit')
                                ->submit('save')
                                ->keyBindings(['mod+s']),
                        ]),
                    ]),
            ]);
    }

    #[Exposed]
    public function save(): void
    {
        abort_unless(static::canAccess(), 403);

        PrivacySetting::current()->update($this->form->getState());

        Notification::make()
            ->success()
            ->title('Nastavení ochrany osobních údajů bylo uloženo')
            ->send();
    }
}
